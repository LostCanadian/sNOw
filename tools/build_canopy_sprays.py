"""Bake leaf attachment geometry on the existing painted branches.

Art-authoring tool only; requires Pillow, NumPy and SciPy. It reads the tree's
alpha mask and writes GDScript coordinates. It does not modify the artwork.
"""
import hashlib
import math
from pathlib import Path
import re
import numpy as np
from PIL import Image
from scipy.spatial import cKDTree

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'scripts/canopy.gd').read_text()
tips_block = source.split('const TWIG_TIPS := [', 1)[1].split(']', 1)[0]
extras_block = source.split('const EXTRA_LEAVES := [', 1)[1].split(']', 1)[0]
tips = [tuple(map(float, values)) for values in re.findall(r'Vector2\(([^,]+),\s*([^\)]+)\)', tips_block)]
extras = [tuple(map(float, values)) for values in re.findall(r'Vector3\(([^,]+),\s*([^,]+),\s*([^\)]+)\)', extras_block)]
anchors = []
for x, y in tips:
    uv = np.array([x / 1024, y / 1536])
    stem = np.array([45, 78]) + uv * [300, 424]
    outward = uv - [0.38, 0.48]
    outward /= np.linalg.norm(outward)
    point = stem + outward * 9
    point[0] = np.clip(point[0], 28, 332)
    point[1] = max(point[1], 92)
    angle = math.atan2(*(point - stem)[::-1]) + math.pi / 2
    anchors.append((stem, angle))
for x, y, angle in extras:
    stem = np.array([45, 78]) + np.array([x / 1024, y / 1536]) * [300, 424]
    point = stem + np.array([math.sin(angle), -math.cos(angle)]) * 7
    point[0] = np.clip(point[0], 24, 336)
    point[1] = max(point[1], 92)
    anchors.append((stem, math.atan2(*(point - stem)[::-1]) + math.pi / 2))
assert len(anchors) == 288
tree_path = ROOT / 'assets/art/season_tree.png'
mask = np.asarray(Image.open(tree_path).convert('RGBA'))[:, :, 3] > 190
# Crown only: keep the exposed ancient lower trunk/root texture.
mask[1100:, :] = False
ys, xs = np.nonzero(mask)
pixels = np.column_stack((xs, ys))
nearest = cKDTree(pixels * [300 / 1024, 424 / 1536])
points = []
for layer in range(1, 10):
    side = -1 if layer % 2 == 0 else 1
    pair = (layer - 1) // 2
    for stem, angle in anchors:
        along = np.array([math.sin(angle), -math.cos(angle)])
        target = stem - along * (4 + pair * 16)
        _, index = nearest.query(target - [45, 78])
        x, y = pixels[index]
        points.append((int(x), int(y), angle + side * (0.55 + pair * 0.12)))
lines = ['extends RefCounted', '## Generated by tools/build_canopy_sprays.py; branch geometry only.',
         '## Tree SHA-256: ' + hashlib.sha256(tree_path.read_bytes()).hexdigest(),
         'const POINTS := [']
lines += ['\tVector3(%d, %d, %.6f),' % point for point in points]
lines += [']', '']
(ROOT / 'scripts/canopy_sprays.gd').write_text('\n'.join(lines))
print('Baked', len(points), 'painted-branch attachment points.')
