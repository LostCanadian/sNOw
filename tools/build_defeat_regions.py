#!/usr/bin/env python3
"""Bake solid sprite bounds from the unchanged twelve-outfit defeat atlas.
Authoring dependencies: Pillow, NumPy, SciPy. This does not edit image pixels.
"""
from pathlib import Path
from PIL import Image
import numpy as np
from scipy.ndimage import label,find_objects
root=Path(__file__).resolve().parents[1]
im=Image.open(root/'assets/art/defeat_wardrobe.png')
alpha=np.array(im)[:,:,3];rects=[]
for row in range(3):
 for col in range(4):
  x=col*im.width//4;y=row*im.height//3
  right=(col+1)*im.width//4;bottom=(row+1)*im.height//3
  components,_=label(alpha[y:bottom,x:right]>180)
  counts=np.bincount(components.ravel());counts[0]=0
  part=find_objects(components)[counts.argmax()-1]
  left=max(x,x+part[1].start-2);top=max(y,y+part[0].start-2)
  endx=min(right,x+part[1].stop+2);endy=min(bottom,y+part[0].stop+2)
  rects.append((left,top,endx-left,endy-top))
(root/'scripts/defeat_regions.gd').write_text('extends RefCounted\n## Generated by tools/build_defeat_regions.py; original PNG pixels are untouched.\nconst RECTS := [\n'+''.join('\tRect2(%d,%d,%d,%d),\n'%r for r in rects)+']\n')
