#!/usr/bin/env python3
"""Bake 144 extra central attachments from the tree's existing painted branch geometry.
Only geometry is read/written; artwork is unchanged. Requires NumPy and SciPy.
"""
from pathlib import Path
import math
import re
import numpy as np
from scipy.spatial import cKDTree

ROOT=Path(__file__).resolve().parents[1]
source=(ROOT/'scripts/canopy.gd').read_text()
def values(block,kind):
 return [tuple(map(float,v)) for v in re.findall(r'Vector'+str(kind)+r'\(([^)]+)\)',block) for v in [v.split(',')]]
tips=values(source.split('const TWIG_TIPS := [',1)[1].split(']',1)[0],2)
extras=values(source.split('const EXTRA_LEAVES := [',1)[1].split(']',1)[0],3)
sprays=values((ROOT/'scripts/canopy_sprays.gd').read_text(),3)
slots=[]
def add(stem,angle,length,min_x=24,min_y=92):
 point=stem+np.array([math.sin(angle),-math.cos(angle)])*length
 point[0]=np.clip(point[0],min_x,360-min_x);point[1]=max(point[1],min_y)
 angle=math.atan2(*(point-stem)[::-1])+math.pi/2
 slots.append([*point,*stem,angle])
for x,y in tips:
 uv=np.array([x/1024,y/1536]);stem=np.array([45,78])+uv*[300,424]
 outward=uv-[.38,.48];outward/=np.linalg.norm(outward)
 add(stem,math.atan2(outward[1],outward[0])+math.pi/2,9,28)
for x,y,angle in extras:add(np.array([45,78])+np.array([x/1024,y/1536])*[300,424],angle,7)
assert len(slots)==288
for layer in range(1,10):
 for base in range(288):
  x,y,angle=sprays[(layer-1)*288+base]
  # Match Godot's integer pair index and deterministic twig spread.
  pair=(layer-1)//2;jitter=math.sin(base*2.399+layer*1.7)*1.7
  add(np.array([45,78])+np.array([x/1024,y/1536])*[300,424],angle,8+pair*1.7+jitter,24,87)
base=np.array(slots[:2016])
candidates=np.array([s for s in slots[2016:] if 105<s[0]<285 and 130<s[1]<335])
chosen=[];points=base[:,:2].tolist()
for _ in range(144):
 distances,_=cKDTree(points).query(candidates[:,:2],k=12)
 # Prefer holes inside the central crown, then spread the new additions.
 weights=distances[:,0]+distances.mean(axis=1)*.15
 index=int(weights.argmax());p=candidates[index];chosen.append(p)
 points.append(p[:2]);candidates=np.delete(candidates,index,axis=0)
lines=['extends RefCounted','## Generated by tools/build_canopy_center.py from existing painted twig anchors.','const POINTS := [']
lines += ['\tVector4(%.6f,%.6f,%.6f,%.6f),'%tuple(p[:4]) for p in chosen]
lines += [']','const ANGLES := [']+['\t%.6f,'%p[4] for p in chosen]+[']','']
(ROOT/'scripts/canopy_center.gd').write_text('\n'.join(lines))
print('Baked',len(chosen),'central crown attachments.')
