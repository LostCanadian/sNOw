#!/usr/bin/env python3
"""Bake silhouette bounds only; retain the generated paper atlas unchanged."""
from pathlib import Path
import numpy as np
from PIL import Image
from scipy.ndimage import label,find_objects
root=Path(__file__).resolve().parents[1]
im=Image.open(root/'assets/art/wildlife.png');alpha=np.array(im)[:,:,3];rects=[]
for row in range(4):
    for col in range(4):
        x=col*im.width//4;y=row*im.height//4
        right=(col+1)*im.width//4;bottom=(row+1)*im.height//4
        parts,_=label(alpha[y:bottom,x:right]>180)
        sizes=np.bincount(parts.ravel());sizes[0]=0
        part=find_objects(parts)[sizes.argmax()-1]
        left=max(x,x+part[1].start-2);top=max(y,y+part[0].start-2)
        endx=min(right,x+part[1].stop+2);endy=min(bottom,y+part[0].stop+2)
        rects.append((left,top,endx-left,endy-top))
(root/'scripts/wildlife_regions.gd').write_text('extends RefCounted\n## Generated by tools/build_wildlife_regions.py; source image pixels are unchanged.\nconst RECTS := [\n'+''.join('\tRect2(%d,%d,%d,%d),\n'%r for r in rects)+']\n')
