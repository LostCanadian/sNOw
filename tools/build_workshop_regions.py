#!/usr/bin/env python3
"""Bake solid alpha bounds in the original paper atlases without changing pixels."""
from pathlib import Path
from PIL import Image
import numpy as np
from scipy.ndimage import label,find_objects
root=Path(__file__).resolve().parents[1]
output='extends RefCounted\n## Generated by tools/build_workshop_regions.py; original PNGs are untouched.\n'
for name,filename,columns,rows in [('UPGRADES','workshop_paper.png',6,5),('TOKENS','workshop_tokens.png',2,1)]:
 im=Image.open(root/'assets/art'/filename);alpha=np.array(im)[:,:,3];rects=[]
 for row in range(rows):
  for col in range(columns):
   x=col*im.width//columns;y=row*im.height//rows
   endx=(col+1)*im.width//columns;endy=(row+1)*im.height//rows
   components,_=label(alpha[y:endy,x:endx]>180)
   counts=np.bincount(components.ravel());counts[0]=0
   part=find_objects(components)[counts.argmax()-1]
   left=max(x,x+part[1].start-2);top=max(y,y+part[0].start-2)
   right=min(endx,x+part[1].stop+2);bottom=min(endy,y+part[0].stop+2)
   rects.append((left,top,right-left,bottom-top))
 output+='const '+name+' := [\n'+''.join('\tRect2(%d,%d,%d,%d),\n'%r for r in rects)+']\n'
(root/'scripts/workshop_regions.gd').write_text(output)
