#!/usr/bin/env python3
"""Reposition redundant sprays onto fine bare branches in the middle-right crown.
Reads the unchanged tree alpha and existing authored coordinates. No pixels change.
Authoring dependencies: Pillow, NumPy, SciPy.
"""
from pathlib import Path
import math,re
import numpy as np
from PIL import Image
from scipy.ndimage import distance_transform_edt,maximum_filter
from scipy.spatial import cKDTree
root=Path(__file__).resolve().parents[1]
source=(root/'scripts/canopy.gd').read_text()
def vectors(text,n):
 return np.array([list(map(float,v.split(','))) for v in re.findall(r'Vector'+str(n)+r'\(([^)]+)\)',text)])
tips=vectors(source.split('const TWIG_TIPS := [')[1].split(']')[0],2)
extras=vectors(source.split('const EXTRA_LEAVES := [')[1].split(']')[0],3)
sprays=vectors((root/'scripts/canopy_sprays.gd').read_text(),3)
centers=vectors((root/'scripts/canopy_center.gd').read_text(),4)
positions=[]
def add(stem,angle,length,minimum=24,min_y=92):
 point=stem+np.array([math.sin(angle),-math.cos(angle)])*length
 point[0]=np.clip(point[0],minimum,360-minimum);point[1]=max(point[1],min_y)
 positions.append(point)
for tip in tips:
 uv=tip/[1024,1536];stem=np.array([45,78])+uv*[300,424]
 outward=uv-[.38,.48];outward/=np.linalg.norm(outward)
 add(stem,math.atan2(outward[1],outward[0])+math.pi/2,9,28)
for x,y,angle in extras:add(np.array([45,78])+[x/1024*300,y/1536*424],angle,7)
for layer in range(1,7):
 for base in range(288):
  x,y,angle=sprays[(layer-1)*288+base]
  add(np.array([45,78])+[x/1024*300,y/1536*424],angle,8+(layer-1)//2*1.7+math.sin(base*2.399+layer*1.7)*1.7,24,87)
positions.extend(centers[:,:2]);positions=np.array(positions)
assert positions.shape==(2160,2)
# The inspected artwork has thin interior twigs above and below the large right
# limb. Select opaque bark there; reject thick limbs even near their edges.
alpha=np.array(Image.open(root/'assets/art/season_tree.png'))[:,:,3]
mask=alpha>220;thickness=distance_transform_edt(mask)
region=np.zeros(mask.shape,dtype=bool);region[360:805,540:870]=True
region &= mask & (maximum_filter(thickness,size=17)<6.5)
ys,xs=np.nonzero(region);pixels=np.column_stack([xs,ys])
stems=pixels/[1024,1536]*[300,424]+[45,78]
# Take donors only from crowded outer/top sprays, retaining all original tips.
neighbors,_=cKDTree(positions).query(positions,k=9)
redundancy=neighbors[:,1:].mean(axis=1)
valid=(np.arange(2160)>=288)&(np.arange(2160)<2016)&((positions[:,0]<155)|(positions[:,0]>300)|(positions[:,1]<170))
donors=np.flatnonzero(valid);donors=donors[np.argsort(redundancy[donors])][:160]
replacements=[]
for i,donor in enumerate(donors):
 angle=np.arctan2(stems[:,1]-275,stems[:,0]-165)+math.pi/2+math.sin(i*2.399)*.85
 points=stems+np.column_stack([np.sin(angle),-np.cos(angle)])*8
 distances,_=cKDTree(np.delete(positions,donor,axis=0)).query(points,k=4)
 # Prefer genuinely open branch space; then spread along the uncovered twigs.
 scores=distances[:,0]+distances.mean(axis=1)*.25
 chosen=int(scores.argmax())
 x,y=pixels[chosen];replacements.append((int(donor),int(x),int(y),float(angle[chosen])))
 positions[donor]=points[chosen]
# The remaining hollow is in the middle of the fork, west of the previous
# right-middle pass. Fine branch tips are sparse here, so use the actual inner
# branches as well, with leaves pointing into the hollow rather than away.
central=np.zeros(mask.shape,dtype=bool);central[600:830,420:610]=True
central &= mask
cy,cx=np.nonzero(central);inner_pixels=np.column_stack([cx,cy])
inner_stems=inner_pixels/[1024,1536]*[300,424]+[45,78]
extra=np.flatnonzero(valid);extra=extra[np.argsort(redundancy[extra])][160:280]
for i,donor in enumerate(extra):
 delta=np.array([194,274])-inner_stems
 angles=np.arctan2(delta[:,1],delta[:,0])+math.pi/2+math.sin(i*2.399)*.85
 points=inner_stems+np.column_stack([np.sin(angles),-np.cos(angles)])*8
 distances,_=cKDTree(np.delete(positions,donor,axis=0)).query(points,k=4)
 weight=np.exp(-np.sum((points-[194,274])**2,axis=1)/(2*28**2))
 scores=(distances[:,0]+distances.mean(axis=1)*.25)*weight
 chosen=int(scores.argmax());x,y=inner_pixels[chosen]
 replacements.append((int(donor),int(x),int(y),float(angles[chosen])))
 positions[donor]=points[chosen]
lines=['extends RefCounted','## Generated by tools/build_canopy_branch_fill.py. Original tree pixels are unchanged.','## (stable slot index, source-image bark x/y, leaf angle).','const REPLACEMENTS := [']
lines+=['\tVector4(%d,%d,%d,%.6f),'%p for p in replacements]+[']','']
(root/'scripts/canopy_branch_fill.gd').write_text('\n'.join(lines))
print('Moved',len(replacements),'redundant outer sprays onto middle-right and central branches.')
