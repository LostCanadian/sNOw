#!/usr/bin/env python3
"""Read the unmodified limb atlas and bake the bounds of each solid sprite.
Alpha specks between pieces are excluded from bounds; no image pixels are edited.
Authoring dependencies: Pillow, NumPy, SciPy.
"""
from pathlib import Path
from PIL import Image
import numpy as np
from scipy.ndimage import label, find_objects
root=Path(__file__).resolve().parents[1]
im=Image.open(root/'assets/art/caretaker_limbs.png')
alpha=np.array(im)[:,:,3]
rects=[]
for row in range(3):
 for col in range(6):
  x=col*im.width//6;y=row*im.height//3
  endx=(col+1)*im.width//6;endy=(row+1)*im.height//3
  components,count=label(alpha[y:endy,x:endx]>180)
  counts=np.bincount(components.ravel());counts[0]=0
  part=find_objects(components)[counts.argmax()-1]
  # Two source pixels of feathering around each silhouette; ankle pegs stay hidden by overlaps.
  left=max(x,x+part[1].start-2);top=max(y,y+part[0].start-2)
  right=min(endx,x+part[1].stop+2);bottom=min(endy,y+part[0].stop+2)
  rects.append((left,top,right-left,bottom-top))
(root/'scripts/limb_regions.gd').write_text('extends RefCounted\n## Generated by tools/build_limb_regions.py; source artwork is unchanged.\nconst RECTS := [\n'+''.join('\tRect2(%d,%d,%d,%d),\n'%rect for rect in rects)+']\n')
