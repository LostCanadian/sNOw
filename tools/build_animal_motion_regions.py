#!/usr/bin/env python3
"""Bake animation crops and stable anchors without modifying generated PNG pixels.
Authoring dependencies: Pillow, NumPy, SciPy. Runtime uses only the baked metadata.
"""
from pathlib import Path
import numpy as np
from PIL import Image
from scipy.ndimage import label,find_objects
ROOT=Path(__file__).resolve().parents[1]
BAT_EYES=((242,164),(236,158),(238,150),(245,142),(248,130),(240,127),(241,126),(240,132))
SHEETS={'owl':('owl_motion',4,4),'squirrel':('squirrel_motion',4,4),'rabbit':('rabbit_motion',8,3),'rare':('rare_motion',4,4)}
lines=['extends RefCounted','## Generated by tools/build_animal_motion_regions.py; source pixels are untouched.']
for name,(filename,cols,rows) in SHEETS.items():
    im=Image.open(ROOT/f'assets/art/{filename}.png');alpha=np.array(im)[:,:,3];rects=[];anchors=[];body_heights=[]
    for row in range(rows):
        y=row*im.height//rows;bottom=(row+1)*im.height//rows
        parts,_=label(alpha[y:bottom,:]>180)
        sizes=np.bincount(parts.ravel());sizes[0]=0
        # A stretched hop can cross a nominal cell boundary. Identify complete
        # silhouettes across each row instead of clipping heads/paws at a grid.
        objects=find_objects(parts)
        ids=np.argsort(sizes)[-cols:]
        chosen=sorted((objects[i-1] for i in ids),key=lambda part:part[1].start)
        for col,part in enumerate(chosen):
            x=col*im.width//cols;right=(col+1)*im.width//cols
            left=max(0,part[1].start-3);top=max(y,y+part[0].start-3)
            endx=min(im.width,part[1].stop+3);endy=min(bottom,y+part[0].stop+3)
            rects.append((left,top,endx-left,endy-top))
            index=row*cols+col
            if name=='rare' and index>=8:
                eye=BAT_EYES[index-8]
                anchor=(x+eye[0]-35,y+eye[1]+20)
            elif name=='owl':
                center=alpha[y:bottom,x+(right-x)*3//8:x+(right-x)*5//8]
                py=np.where(center>180)[0];foot=y+int(py.max())+1
                band_left=x+(right-x)//4;band_right=x+(right-x)*3//4
                _,px=np.where(alpha[max(y,foot-10):foot,band_left:band_right]>180)
                anchor=(band_left+(int(px.min())+int(px.max()))/2,foot)
                body_heights.append(foot-y-int(py.min()))
            else:anchor=((left+endx)/2,endy-2)
            anchors.append(anchor)
    lines.append(f'const {name.upper()}_RECTS := [')
    lines.extend('\tRect2(%d,%d,%d,%d),'%r for r in rects);lines.append(']')
    lines.append(f'const {name.upper()}_ANCHORS := [')
    lines.extend('\tVector2(%.2f,%.2f),'%p for p in anchors);lines.append(']')
    if name=='owl':lines.append('const OWL_BODY_HEIGHTS := '+str(body_heights))
(ROOT/'scripts/animal_motion_regions.gd').write_text('\n'.join(lines)+'\n')
print('Baked 72 motion frames and stable source-space anchors.')
